"""Write docs/openapi.json from the code, or check that it still matches it.

Run from the repository root: python toolgate/scripts/export_openapi.py [--check]
docs/openapi.json is the API reference the README links to. Regenerated by hand, it fell
behind the routes (it still said 0.2.2); now CI fails when it differs from the app.

Keys are sorted, so the file changes only when the API does. The app is built with its data
in a temporary folder, the way the tests build it: importing it creates its data folder, and
that must never be the checkout or a real install's.
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DOCUMENT = Path("docs/openapi.json")

sys.path.insert(0, str(REPO))


def render() -> str:
    with tempfile.TemporaryDirectory(prefix="toolgate-openapi-") as data:
        os.environ["TOOLGATE_DATA_DIR"] = data
        os.environ["TOOLGATE_ENV_PATH"] = str(Path(data) / ".env")
        os.environ["TOOLGATE_VAULT_KEY_FILE"] = str(Path(data) / "vault.key")
        from toolgate.api.server import app

        document = app.openapi()
    return json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    text = render()
    path = REPO / DOCUMENT
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == text:
        return 0
    if check:
        print(f"{DOCUMENT} differs from the code; run python toolgate/scripts/export_openapi.py")
        return 1
    path.write_bytes(text.encode("utf-8"))
    print(f"wrote {DOCUMENT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
